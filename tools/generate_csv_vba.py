def schema_module(contract: dict[str, Any]) -> str:
    check_supported(contract)
    types = contract["types"]
    constants = [
        ("CSV_CONTRACT_VERSION", "Long", str(contract["contract_version"]), "Contract version"),
        ("CSV_DELIMITER", "String", vba_string(contract["format"]["delimiter"]), "Field separator"),
        ("CSV_MAX_BYTES", "Long", str(contract["format"]["max_bytes"]), "Largest file, in bytes"),
        ("CSV_MAX_DIGITS", "Long", str(contract["format"]["max_significant_digits"]), "Significant digits of a number"),
        ("CSV_ID_MAX_LENGTH", "Long", str(types["id"]["max_length"]), "Characters of an identifier"),
        ("CSV_ID_FORBIDDEN", "String", vba_string(types["id"]["forbidden"]), "Characters an identifier may not hold"),
        ("CSV_TEXT_MAX_LENGTH", "Long", str(types["text"]["max_length"]), "Characters of a text"),
        ("CSV_FLAG_VALUES", "String", vba_string(joined(types["flag"]["allowed"])), "Allowed values of a flag"),
        ("CSV_DATE_MIN", "String", vba_string(types["date"]["min"]), "Earliest date, yyyy-mm-dd"),
        ("CSV_DATE_MAX", "String", vba_string(types["date"]["max"]), "Latest date, yyyy-mm-dd"),
    ]
    width = max(len(name) for name, _, _, _ in constants)
    lines = [SCHEMA_HEADER.rstrip("\n")]
    for name, kind, value, comment in constants:
        lines.append(f"        Public Const {name.ljust(width)} As {kind} = {value}    '{comment}")
    lines.append(SCHEMA_TYPES.rstrip("\n"))
    for kind, spec in contract["files"].items():
        columns, rules = spec["columns"], spec.get("row_rules", [])
        lines += [f'            Case "{kind}"',
                  f'                Spec.Kind = "{kind}"',
                  f'                Spec.Sheet = {vba_string(spec["sheet"])}',
                  f'                Spec.Key = {vba_string(spec["key"])}',
                  f'                Spec.ReservedKeys = {vba_string(joined(spec.get("reserved_keys", [])))}',
                  f'                Spec.MaxRecords = {spec["max_records"]}',
                  f'                Spec.ColumnCount = {len(columns)}',
                  f'                ReDim Columns(1 To {len(columns)})']
        for index, column in enumerate(columns, start=1):
            allowed = column.get("allowed", types["flag"]["allowed"] if column["type"] == "flag" else [])
            bounds = []
            for key in ("min", "min_exclusive", "max"):
                bounds += [vba_bool(key in column), vba_number(column.get(key, 0))]
            arguments = [vba_string(column["name"]), vba_string(column["type"]), vba_bool(column["required"]),
                         vba_string(joined(allowed))] + bounds
            lines.append(f"                SetColumn Columns({index}), " + ", ".join(arguments))
        lines.append(f"                Spec.RuleCount = {len(rules)}")
        if rules:
            lines.append(f"                ReDim Rules(1 To {len(rules)})")
        else:
            lines.append("                Erase Rules")
        for index, rule in enumerate(rules, start=1):
            if "when" in rule:
                values = [rule["id"], "when", joined(list(rule["when"])), joined(list(rule["when"].values())),
                          joined(rule["required"]), joined(rule["otherwise_blank"]), "", ""]
                names = list(rule["when"]) + rule["required"] + rule["otherwise_blank"]
            else:
                key = "after" if "after" in rule else "above"
                values = [rule["id"], key, "", "", "", "", rule[key][0], rule[key][1]]
                names = list(rule[key])
            unique = list(dict.fromkeys(names))
            arguments = [vba_string(value) for value in values + [joined(unique)]]
            lines.append(f"                SetRule Rules({index}), " + ", ".join(arguments))
        lines.append("                CsvSpecOf = True")
    lines.append(SCHEMA_FOOTER.rstrip("\n"))
    return "\r\n".join(lines) + "\r\n"


