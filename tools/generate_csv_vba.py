def hex_lines(variable: str, data: bytes) -> list[str]:
    text = data.hex().upper()
    if not text:
        return [f'        {variable} = ""']
    chunks = [text[i:i + 2 * HEX_PER_LINE] for i in range(0, len(text), 2 * HEX_PER_LINE)]
    return [f'        {variable} = "{chunks[0]}"'] + [f'        {variable} = {variable} & "{chunk}"' for chunk in chunks[1:]]


def pieces(value: str, size: int = 120) -> list[str]:
    """VBA string expressions that concatenate to value, each short enough for one line."""
    return [vba_string(value[i:i + size]) for i in range(0, len(value), size)]


def expected_lines(findings: list[list[Any]]) -> list[str]:
    """Statements that build Expected: every finding as code|line|record|column, one per line."""
    lines = ['        Expected = ""']
    for index, (code, line, record, column) in enumerate(findings):
        separator = "Expected & vbLf & " if index else ""
        lines.append(f"        Expected = {separator}{vba_string(f'{code}|{line}|{record}|{column}')}")
    return lines


def values_lines(variable: str, rows: list[dict[str, str]]) -> list[str]:
    """Statements that build every value: fields separated by ChrW(31), records by ChrW(30)."""
    lines = [f'        {variable} = ""']
    for r, row in enumerate(rows):
        for c, value in enumerate(row.values()):
            separator = "ChrW(30)" if r and not c else "ChrW(31)" if c else ""
            parts = ([separator] if separator else []) + pieces(value)
            for part in parts:
                lines.append(f"        {variable} = {variable} & {part}")
    return lines


def tests_module(root: Path, contract: dict[str, Any]) -> str:
    expected = json.loads((root / EXPECTED).read_text(encoding="utf-8"))["fixtures"]
    cases = json.loads((root / CASES).read_text(encoding="utf-8"))["cases"]
    procedures: list[list[str]] = []
    calls: list[str] = []
    case_count = check_count = 0
    for number, (name, entry) in enumerate(sorted(expected.items()), start=1):
        data = (root / FIXTURES / name).read_bytes()
        rows, found = validate(data, entry["kind"], contract)
        if [[f.code, f.line, f.record, f.column] for f in found] != entry["findings"]:
            raise ValueError(f"{name}: findings differ from {EXPECTED}; fix the fixtures first")
        kept, _ = validate(data, entry["kind"], contract, keep_records=True)
        procedure = f"Fixture{number:02d}"
        calls.append(f"        {procedure}")
        lines = [f"Private Sub {procedure}()", f"    'Fixture {name}.", "    Dim HexText     As String    'The file",
                 "    Dim Expected    As String    'Its findings", "    Dim Values      As String    'Its values"]
        lines += hex_lines("HexText", data) + expected_lines(entry["findings"]) + values_lines("Values", rows)
        lines.append(f'        RunFixture {vba_string(name)}, "{entry["kind"]}", HexText, Expected, {entry["records"]}, Values, '
                     f'{vba_bool(readable(found))}, {len(kept)}')
        lines.append("")
        lines.append("End Sub")
        procedures.append(lines)
        case_count += 3
        check_count += 3 * 3 + (2 if rows else 0)
    for number, case in enumerate(cases, start=1):
        data = case_bytes(case)
        rows, found = validate(data, case["kind"], contract, max_records=case.get("max_records"),
                               max_bytes=case.get("max_bytes"))
        if [[f.code, f.line, f.record, f.column] for f in found] != case["findings"]:
            raise ValueError(f"{CASES}: case {case['name']}: findings differ; fix the case first")
        kept, _ = validate(data, case["kind"], contract, max_records=case.get("max_records"),
                           max_bytes=case.get("max_bytes"), keep_records=True)
        procedure = f"Case{number:02d}"
        calls.append(f"        {procedure}")
        lines = [f"Private Sub {procedure}()", f"    'Case {case['name']}.", "    Dim HexText     As String    'The content",
                 "    Dim Expected    As String    'Its findings", "    Dim Values      As String    'Its values"]
        lines += hex_lines("HexText", data) + expected_lines(case["findings"]) + values_lines("Values", rows)
        lines.append(f'        RunInline {vba_string(case["name"])}, "{case["kind"]}", HexText, {case.get("max_records", 0)}, '
                     f'{case.get("max_bytes", 0)}, Expected, {case["records"]}, Values, '
                     f'{vba_bool(readable(found))}, {len(kept)}')
        lines.append("")
        lines.append("End Sub")
        procedures.append(lines)
        case_count += 1
        check_count += 3 + (1 if rows else 0)
    portfolio = json.loads((root / PORTFOLIO).read_text(encoding="utf-8"))["cases"]
    for number, case in enumerate(portfolio, start=1):
        data = str(case["text"]).encode("utf-8")
        staged, found = validate_records(data, "Trades", contract, keep_records=True)
        between = check_portfolio(staged, case["netting_sets"], contract)
        if not readable(found) or [[f.code, f.line, f.record, f.column] for f in between] != case["findings"]:
            raise ValueError(f"{PORTFOLIO}: case {case['name']}: findings differ; fix the case first")
        if any("|" in key for key in case["netting_sets"]) or not case["netting_sets"]:
            raise ValueError(f"{PORTFOLIO}: case {case['name']}: netting sets must be given, without '|'")
        procedure = f"Portfolio{number:02d}"
        calls.append(f"        {procedure}")
        lines = [f"Private Sub {procedure}()", f"    'Portfolio case {case['name']}.",
                 "    Dim HexText     As String    'The Trades file", "    Dim Expected    As String    'Its findings"]
        lines += hex_lines("HexText", data) + expected_lines(case["findings"])
        lines.append(f'        RunPortfolio {vba_string(case["name"])}, HexText, {vba_string("|".join(case["netting_sets"]))}, '
                     "Expected")
        lines.append("")
        lines.append("End Sub")
        procedures.append(lines)
        case_count += 1
        check_count += 1
    staged_cases = json.loads((root / STAGED).read_text(encoding="utf-8"))["cases"]
    for number, case in enumerate(staged_cases, start=1):
        names = [column["name"] for column in contract["files"][case["kind"]]["columns"]]
        staged_rows = [(row["line"], row["values"]) for row in case["rows"]]
        found = check_staged(case["kind"], staged_rows, contract, max_records=case.get("max_records"))
        if [[f.code, f.line, f.record, f.column] for f in found] != case["findings"]:
            raise ValueError(f"{STAGED}: case {case['name']}: findings differ; fix the case first")
        procedure = f"Staged{number:02d}"
        calls.append(f"        {procedure}")
        lines = [f"Private Sub {procedure}()", f"    'Staged case {case['name']}.",
                 "    Dim RowText     As String    'The rows", "    Dim Expected    As String    'Their findings"]
        lines += values_lines("RowText", [{name: given.get(name, "") for name in names} for _, given in staged_rows])
        lines += expected_lines(case["findings"])
        lines.append(f'        RunStaged {vba_string(case["name"])}, "{case["kind"]}", RowText, '
                     f'{vba_string("|".join(str(line) for line, _ in staged_rows))}, {case.get("max_records", 0)}, Expected')
        lines.append("")
        lines.append("End Sub")
        procedures.append(lines)
        case_count += 1
        check_count += 1
    # The file cases: unknown kind 1, missing file 1, round trip 3, too large 2, malformed path 1,
    # ReadCsv_Silent 2.
    case_count += 6
    check_count += 1 + 1 + 3 + 2 + 1 + 2
    rejected = (root / FIXTURES / REJECTED_FIXTURE).read_bytes()
    _, rejected_found = validate(rejected, "Trades", contract)
    if not rejected_found:
        raise ValueError(f"{REJECTED_FIXTURE} must be rejected for the ReadCsv_Silent case")
    first = rejected_found[0]
    trip = (root / FIXTURES / "valid/trades.csv").read_bytes()
    trip_rows, trip_found = validate(trip, "Trades", contract)
    if trip_found or not trip_rows:
        raise ValueError("valid/trades.csv must be accepted for the file round trip")
    _, records = parse_records(trip)
    out = [TESTS_HEADER.rstrip("\n"),
           f"        Private Const EXPECTED_CASES    As Long = {case_count}    'Cases in a complete run",
           f"        Private Const EXPECTED_CHECKS   As Long = {check_count}    'Checks in a complete run",
           f"        Private Const ROUND_TRIP_LAST_LINE As Long = {records[-1].line}    'Line of the last record of valid/trades.csv",
           f'        Private Const ROUND_TRIP_RESULT As String = "RESULT=ACCEPTED; records={len(trip_rows)}"    \'ReadCsv_Silent on it',
           f'        Private Const REJECTED_RESULT   As String = "RESULT=REJECTED; findings={len(rejected_found)}; '
           f'first={first.code}|{first.line}|{first.record}|{first.column}"    \'ReadCsv_Silent on {REJECTED_FIXTURE}',
           TESTS_RUNNER.rstrip("\n")]
    out += calls
    out.append(TESTS_FOOTER.rstrip("\n"))
    out += ["", "", "'", "'" + "-" * 78, "'", "'" + "FILES AND CASES".center(78).rstrip(), "'", "'" + "-" * 78, "'", ""]
    for lines in procedures:
        out += lines + ["", ""]
    out += ["Private Function RoundTripHex() As String", "    'valid/trades.csv, for the file cases.",
            "    Dim HexText As String    'The file"]
    out += hex_lines("HexText", trip)
    out += ["        RoundTripHex = HexText", "", "End Function", "", "",
            "Private Function RoundTripValues() As String", "    'The values of valid/trades.csv.",
            "    Dim Values As String    'The values"]
    out += values_lines("Values", trip_rows)
    out += ["        RoundTripValues = Values", "", "End Function", "", "",
            "Private Function RejectedHex() As String", f"    '{REJECTED_FIXTURE}, for ReadCsv_Silent.",
            "    Dim HexText As String    'The file"]
    out += hex_lines("HexText", rejected)
    out += ["        RejectedHex = HexText", "", "End Function"]
    return "\r\n".join(out) + "\r\n"


def parse_records(data: bytes) -> tuple[str, list[Any]]:
    from csv_contract import decode, parse
    text, _ = decode(data)
    records, _ = parse(text or "")
    return text or "", records


def case_bytes(case: dict[str, Any]) -> bytes:
    """The content of an inline case: its hex bytes, or its text as UTF-8."""
    return bytes.fromhex(case["hex"]) if "hex" in case else str(case["text"]).encode("utf-8")


def generate(root: Path) -> dict[str, str]:
    contract = load_contract(root)
    modules = {SCHEMA: schema_module(contract), TESTS: tests_module(root, contract)}
    return {path: content.replace("\r\n", "\n").replace("\n", "\r\n") for path, content in modules.items()}


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[1])
    parser.add_argument("--check", action="store_true", help="fail if a module is out of date")
    options = parser.parse_args()
    root = options.root.resolve()
    try:
        modules = generate(root)
    except (OSError, ValueError, KeyError) as error:
        print(f"ERROR: {error}", file=sys.stderr)
        return 2
    stale = []
    for path, content in modules.items():
        target = root / path
        if options.check:
            current = target.read_bytes().decode("cp1252").replace("\r\n", "\n") if target.exists() else None
            if current != content.replace("\r\n", "\n"):
                stale.append(path)
            continue
        target.write_bytes(content.encode("cp1252"))
        print(f"wrote {path}")
    if stale:
        print("out of date: " + ", ".join(stale) + "; run python tools/generate_csv_vba.py")
        return 1
    if options.check:
        print("generated CSV modules are up to date")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
