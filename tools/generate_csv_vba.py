# What the reader implements for each type; a contract that asks for anything else needs reader code first.
TYPES = {"id": {"max_length", "forbidden"}, "text": {"max_length"}, "code": set(), "flag": {"allowed"},
         "currency": {"pattern"}, "integer": set(), "number": set(), "date": {"min", "max"}}
CURRENCY_PATTERN = "^[A-Z]{3}$"
# Bytes per VBA string literal of hex, so that a line stays near 100 columns.
HEX_PER_LINE = 80


def vba_string(value: str) -> str:
    """A VBA string expression for value; characters outside printable ASCII become ChrW calls."""
    parts: list[str] = []
    literal = ""
    for char in value:
        if " " <= char <= "~":
            literal += '""' if char == '"' else char
            continue
        if literal:
            parts.append(f'"{literal}"')
            literal = ""
        parts.append(f"ChrW({ord(char)})" if ord(char) < 0x10000 else
                     f"ChrW({0xD800 + ((ord(char) - 0x10000) >> 10)}) & ChrW({0xDC00 + ((ord(char) - 0x10000) & 0x3FF)})")
    if literal or not parts:
        parts.append(f'"{literal}"')
    return " & ".join(parts)


def vba_number(value: float) -> str:
    """A locale-independent VBA numeric literal."""
    return repr(float(value)) if not float(value).is_integer() else str(int(value))


def vba_bool(value: bool) -> str:
    return "True" if value else "False"


def joined(values: list[str]) -> str:
    if any("|" in value for value in values):
        raise ValueError(f"a listed value contains '|': {values}")
    return "|".join(values)


def check_supported(contract: dict[str, Any]) -> None:
    """Refuse a contract the generated module and the reader cannot express."""
    if contract["format"]["delimiter"] != DELIMITER or FORMULA_START != ("=", "+", "-", "@", "\t", "\r"):
        raise ValueError("delimiter or formula characters differ from what CORE_CsvReader implements")
    if set(contract["types"]) != set(TYPES):
        raise ValueError(f"types {sorted(contract['types'])} differ from what CORE_CsvReader implements")
    for kind, keys in TYPES.items():
        if set(contract["types"][kind]) != keys:
            raise ValueError(f"type {kind}: settings {sorted(contract['types'][kind])} are not supported")
    if contract["types"]["currency"]["pattern"] != CURRENCY_PATTERN:
        raise ValueError("currency pattern differs from what CORE_CsvReader implements")
    for spec in contract["files"].values():
        for rule in spec.get("row_rules", []):
            if not ({"when", "required", "otherwise_blank"} == set(rule) - {"id"} or
                    set(rule) - {"id"} in ({"after"}, {"above"})):
                raise ValueError(f"row rule {rule['id']} has a form CORE_CsvReader does not implement")


